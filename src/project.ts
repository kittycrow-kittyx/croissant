import fs from "node:fs";
import path from "node:path";
import ts from "typescript";
import { Context } from "./context.js";
import { Emitter } from "./emitter.js";

type Named<T> = { name: string; declaration: T };
export interface ProjectInputs {
  destination: string;
  context: Context;
  emitter: Emitter;
  sources: readonly ts.SourceFile[];
  types: readonly string[];
  intrinsics: ReadonlyMap<string, ts.FunctionDeclaration>;
  globals: readonly Named<ts.VariableDeclaration>[];
  functions: readonly Named<ts.FunctionDeclaration>[];
}
export interface ProjectResult {
  directory: string;
  generatedFiles: readonly string[];
}

const banner = "/* Generated by Croissant from Bake --target=clang. Do not edit. */";
const guards = (name: string, lines: string[]): string => {
  const guard = "CROISSANT_" + name.replace(/[^A-Za-z0-9]/g, "_").toUpperCase() + "_H";
  return [banner, "#ifndef " + guard, "#define " + guard, ...lines,
    "#endif /* " + guard + " */", ""].join("\n");
};
const nativeNumbers = [
  "extern int32_t croissant_js_and(double, double);",
  "extern int32_t croissant_js_or(double, double);",
  "extern int32_t croissant_js_xor(double, double);",
  "extern int32_t croissant_js_shl(double, double);",
  "extern int32_t croissant_js_shr(double, double);",
  "extern uint32_t croissant_js_ushr(double, double);",
  "extern int32_t croissant_js_not(double);",
  "extern double croissant_js_remainder(double, double);"
];
function write(root: string, file: string, lines: string, output: string[]): void {
  const absolute = path.join(root, file);
  fs.mkdirSync(path.dirname(absolute), { recursive: true });
  fs.writeFileSync(absolute, lines.endsWith("\n") ? lines : lines + "\n");
  output.push(file);
}

/** Materialise a real multi-translation-unit C project, not a split text dump. */
export function emitProject(input: ProjectInputs): ProjectResult {
  const { context, emitter, sources, globals, functions } = input;
  const destination = path.resolve(input.destination);
  const parent = path.dirname(destination);
  const scratch = path.join(parent, "." + path.basename(destination) + ".stage-" + process.pid);
  const backup = path.join(parent, "." + path.basename(destination) + ".previous-" + process.pid);
  if (destination === context.root || destination.startsWith(context.root + path.sep))
    throw new Error("CR401: output must not overwrite the Bake input");
  const modules = sources.map(source => {
    const relative = path.relative(context.root, source.fileName).split(path.sep).join("/");
    if (relative.startsWith("../") || !relative.endsWith(".ts"))
      throw new Error("CR402: source path escapes Bake root: " + relative);
    return { source, module: relative.slice(0, -3) };
  });
  if (new Set(modules.map(item => item.module)).size !== modules.length)
    throw new Error("CR403: duplicate generated module path");
  fs.mkdirSync(parent, { recursive: true });
  fs.rmSync(scratch, { recursive: true, force: true });
  fs.rmSync(backup, { recursive: true, force: true });
  const output: string[] = [];
  const ownFunctions = (source: ts.SourceFile) =>
    functions.filter(entry => entry.declaration.getSourceFile() === source);
  const cSourcePaths = modules.map(item => "src/" + item.module + ".c");
  try {
    write(scratch, "include/croissant/types.h", guards("types", [
      "#include <stdint.h>", "#include <stdbool.h>", "#include <stddef.h>", "",
      ...input.types
    ]), output);
    write(scratch, "include/croissant/intrinsics.h", guards("intrinsics", [
      '#include "croissant/types.h"', "", ...nativeNumbers, "",
      ...[...input.intrinsics].map(([name, decl]) =>
        (name === "__bake_c_abort_range" ? "__attribute__((noreturn)) " : "") +
        emitter.functionSignature(decl, name) + ";")
    ]), output);
    write(scratch, "include/croissant/globals.h", guards("globals", [
      '#include "croissant/types.h"', "",
      ...globals.map(item => "extern " + context.type(item.declaration.type, item.declaration.name) +
        " " + item.name + ";"),
      "", "void croissant_init_globals(void);"
    ]), output);
    for (const item of modules) {
      write(scratch, "include/croissant/" + item.module + ".h",
        guards("module_" + item.module, [
          '#include "croissant/types.h"', "",
          ...ownFunctions(item.source).map(entry =>
            emitter.functionSignature(entry.declaration, entry.name) + ";")
        ]), output);
    }
    write(scratch, "include/croissant/all.h", guards("all", [
      '#include "croissant/types.h"',
      '#include "croissant/intrinsics.h"',
      '#include "croissant/globals.h"',
      ...modules.map(item => '#include "croissant/' + item.module + '.h"')
    ]), output);
    const initialisations = [
      banner, '#include "croissant/all.h"', "",
      ...globals.map(item => context.type(item.declaration.type, item.declaration.name) +
        " " + item.name + ";"), "",
      "void croissant_init_globals(void) {",
      ...globals.map(item => {
        const initial = item.declaration.initializer;
        if (!initial) context.fail(item.declaration, "CR308", "uninitialised top-level native variable");
        return "  " + item.name + " = " +
          emitter.expression(initial, context.type(item.declaration.type, item.declaration.name)) + ";";
      }), "}"
    ];
    write(scratch, "src/globals.c", initialisations.join("\n"), output);
    for (const item of modules) {
      const definitions = ownFunctions(item.source).map(entry => {
        if (!entry.declaration.body)
          context.fail(entry.declaration, "CR309", "missing native function body");
        return emitter.function(entry.declaration, entry.name);
      });
      write(scratch, "src/" + item.module + ".c",
        [banner, '#include "croissant/all.h"', "", ...definitions].join("\n"), output);
    }
    write(scratch, "CMakeLists.txt", [
      "cmake_minimum_required(VERSION 3.20)",
      "project(croissant_thistle LANGUAGES C)",
      "set(CMAKE_C_STANDARD 11)",
      "set(CMAKE_C_STANDARD_REQUIRED ON)",
      "add_library(croissant_thistle OBJECT",
      "  src/globals.c",
      ...cSourcePaths.map(p => "  " + p),
      ")",
      "target_include_directories(croissant_thistle PUBLIC include)",
      "target_compile_options(croissant_thistle PRIVATE -ffreestanding -fno-builtin -fno-stack-protector)",
      ""
    ].join("\n"), output);
    write(scratch, "croissant.manifest.json", JSON.stringify({
      schema: 1, generator: "Croissant", input: "Bake --target=clang",
      format: "modular-freestanding-c", intrinsicAbi: 1,
      modules: modules.map(item => ({
        input: item.module + ".ts", source: "src/" + item.module + ".c",
        header: "include/croissant/" + item.module + ".h",
        functions: ownFunctions(item.source).length
      })),
      sources: ["src/globals.c", ...cSourcePaths],
      headers: ["include/croissant/all.h", "include/croissant/types.h",
        "include/croissant/intrinsics.h", "include/croissant/globals.h",
        ...modules.map(item => "include/croissant/" + item.module + ".h")]
    }, null, 2), output);
    if (fs.existsSync(destination)) fs.renameSync(destination, backup);
    try {
      fs.renameSync(scratch, destination);
    } catch (error) {
      if (fs.existsSync(backup)) fs.renameSync(backup, destination);
      throw error;
    }
    fs.rmSync(backup, { recursive: true, force: true });
    return { directory: destination, generatedFiles: output };
  } finally {
    fs.rmSync(scratch, { recursive: true, force: true });
  }
}
